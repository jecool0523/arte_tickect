import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
const read = file => readFileSync(new URL(`../${file}`,import.meta.url),"utf8")
const db = JSON.parse(read("database/schema.snapshot.json"))
const history = JSON.parse(read("database/migrations.snapshot.json"))
assert.deepEqual(db.migration,history.migrations.at(-1))
assert.equal(db.tables.length,14)
assert.ok(db.tables.every(t => t.rls && t.description))
for (const table of ["arte_musical_tickets","dead_poets_society_bookings","rent_bookings","toctoc_bookings"]) {
  for (const column of ["status","booking_date"]) assert.equal(db.columns.find(c => c.table === `public.${table}` && c.column === column)?.nullable,"NO")
  assert.ok(db.indexes.some(i => i.name === `idx_${table}_owner_date` && i.definition.includes("(user_id, booking_date DESC)")))
  assert.ok(db.constraints.some(c => c.table === `public.${table}` && c.name === `${table}_status_check` && c.validated))
  const seats = db.constraints.find(c => c.name === `${table}_seats_nonempty_check`)
  assert.ok(seats.validated); assert.ok(!seats.definition.includes("<= 10"),"Historic large bookings must remain")
}
for (const name of ["arte_period_musical_unique","reviews_fan_user_id_idx"]) assert.ok(!db.indexes.some(i=>i.name===name))
assert.ok(db.constraints.some(c=>c.name==="performance_settings_period_fkey" && c.validated && c.definition.includes("ON DELETE RESTRICT")))
assert.ok(db.constraints.some(c=>c.name==="booking_period_time_order" && c.validated))
assert.ok(db.constraints.some(c=>c.name==="reviews_rating_range" && c.validated))
const definitions = db.indexes.map(i=>`${i.table}:${i.definition.replace(/^CREATE (UNIQUE )?INDEX \S+ ON /,"$1")}`)
assert.equal(new Set(definitions).size,definitions.length,"No exact duplicate indexes")
const generated = read("types/database.generated.ts")
assert.match(generated,/is_admin: boolean/); assert.match(generated,/is_presale_user: boolean/)
assert.match(generated,/deletion_token_hash: string \| null/)
assert.match(generated,/performance_settings_period_fkey/)
assert.doesNotMatch(generated,/admin_get_booking_stats:|is_current_user_presale:|admin_delete_review:/)
assert.doesNotMatch(read("types/supabase.ts"),/admin_get_booking_stats:|is_current_user_presale:/)
const sql = read("database/changes/schema-organization.sql")
assert.doesNotMatch(sql,/\b(?:delete\s+from|truncate|drop\s+table|drop\s+schema|rename\s+to|cascade)\b/i,"No destructive data reorganization")
assert.match(sql,/lock_timeout/)
console.log("Database metadata, constraints, owner indexes, retained legacy model, generated types and schema-only cleanup passed.")
